@pytest.mark.parametrize("layout", ["none", "root", "www", "both"])
def test_data_root_matches_game_tools(tmp_path: Path, layout: str):
    from core.game_tools import rpgm_data_root

    for base in {
        "root": [tmp_path],
        "www": [tmp_path / "www"],
        "both": [tmp_path, tmp_path / "www"],
    }.get(layout, []):
        (base / "data").mkdir(parents=True)
        (base / "data" / "System.json").write_text("{}")
    assert game_native_size._data_root(str(tmp_path)) == rpgm_data_root(str(tmp_path))  # pyright: ignore[reportPrivateUsage]
