import json
from pathlib import Path

import pytest

from core import game_native_size
from core.game_native_size import NativeSize, detect_native_size

MANAGERS = (
    "SceneManager._screenWidth       = {w};\nSceneManager._screenHeight      = {h};\n"
)


def make_mz(
    root: Path, advanced: object, *, www: bool = False, bom: bool = False
) -> Path:
    base = root / "www" if www else root
    (base / "data").mkdir(parents=True)
    text = json.dumps({"gameTitle": "Test", "advanced": advanced})
    (base / "data" / "System.json").write_text(
        ("﻿" if bom else "") + text, encoding="utf-8"
    )
    return root


def make_mv(
    root: Path,
    *,
    managers: tuple[int, int] | None = (816, 624),
    plugins: list[dict[str, object]] | None = None,
    plugins_text: str | None = None,
    www: bool = False,
) -> Path:
    base = root / "www" if www else root
    (base / "data").mkdir(parents=True)
    (base / "js").mkdir()
    (base / "data" / "System.json").write_text(
        '{"gameTitle": "Test"}', encoding="utf-8"
    )
    (base / "js" / "rpg_core.js").write_text("// core\n")
    if managers is not None:
        (base / "js" / "rpg_managers.js").write_text(
            MANAGERS.format(w=managers[0], h=managers[1])
        )
    if plugins_text is None and plugins is not None:
        plugins_text = (
            "// Generated by RPG Maker.\nvar $plugins =\n"
            + json.dumps(plugins, indent=0)
            + ";\n"
        )
    if plugins_text is not None:
        (base / "js" / "plugins.js").write_text(plugins_text)
    return root


def plugin(name: str, status: bool, **params: str) -> dict[str, object]:
    return {"name": name, "status": status, "description": "", "parameters": params}


def yep(width: str, height: str, status: bool = True) -> dict[str, object]:
    return plugin(
        "YEP_CoreEngine", status, **{"Screen Width": width, "Screen Height": height}
    )


def community(width: str, height: str, status: bool = True) -> dict[str, object]:
    return plugin("Community_Basic", status, screenWidth=width, screenHeight=height)


# MZ


def test_mz_size(tmp_path: Path):
    folder = make_mz(tmp_path, {"screenWidth": 1280, "screenHeight": 720})
    assert detect_native_size(str(folder)) == NativeSize(1280, 720, "data/System.json")


def test_mz_www_layout(tmp_path: Path):
    folder = make_mz(tmp_path, {"screenWidth": 1280, "screenHeight": 720}, www=True)
    assert detect_native_size(str(folder)) == NativeSize(
        1280, 720, "www/data/System.json"
    )


def test_mz_bom(tmp_path: Path):
    folder = make_mz(tmp_path, {"screenWidth": 1600, "screenHeight": 900}, bom=True)
    assert detect_native_size(str(folder)) == NativeSize(1600, 900, "data/System.json")


def test_damaged_system_json(tmp_path: Path):
    (tmp_path / "data").mkdir()
    (tmp_path / "data" / "System.json").write_text('{"advanced": {"screenWidth": 12')
    assert detect_native_size(str(tmp_path)) is None


def test_system_json_not_an_object(tmp_path: Path):
    (tmp_path / "data").mkdir()
    (tmp_path / "data" / "System.json").write_text("[1, 2]")
    assert detect_native_size(str(tmp_path)) is None


def test_mz_missing_advanced(tmp_path: Path):
    (tmp_path / "data").mkdir()
    (tmp_path / "data" / "System.json").write_text('{"gameTitle": "x"}')
    assert detect_native_size(str(tmp_path)) is None


@pytest.mark.parametrize(
    "advanced",
    [
        {"screenWidth": 0, "screenHeight": 720},
        {"screenWidth": 1280, "screenHeight": 16385},
        {"screenWidth": "1280", "screenHeight": 720},
        {"screenWidth": True, "screenHeight": 720},
        {"screenWidth": 1280},
    ],
)
def test_mz_invalid_sizes(tmp_path: Path, advanced: dict[str, object]):
    assert detect_native_size(str(make_mz(tmp_path, advanced))) is None


def test_mz_side_limits(tmp_path: Path):
    folder = make_mz(tmp_path, {"screenWidth": 16384, "screenHeight": 1})
    assert detect_native_size(str(folder)) == NativeSize(16384, 1, "data/System.json")


def test_file_too_large(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    folder = make_mz(tmp_path, {"screenWidth": 1280, "screenHeight": 720})
    monkeypatch.setattr(game_native_size, "MAX_FILE_BYTES", 10)
    assert detect_native_size(str(folder)) is None


# MV


def test_plain_mv(tmp_path: Path):
    folder = make_mv(tmp_path, plugins=[])
    assert detect_native_size(str(folder)) == NativeSize(816, 624, "js/rpg_managers.js")


def test_mv_without_managers_uses_default(tmp_path: Path):
    folder = make_mv(tmp_path, managers=None)
    assert detect_native_size(str(folder)) == NativeSize(816, 624, "MV default")


def test_mv_edited_managers(tmp_path: Path):
    folder = make_mv(tmp_path, managers=(1024, 768), www=True)
    assert detect_native_size(str(folder)) == NativeSize(
        1024, 768, "www/js/rpg_managers.js"
    )


def test_mv_managers_with_one_side_missing(tmp_path: Path):
    folder = make_mv(tmp_path, managers=None)
    (tmp_path / "js" / "rpg_managers.js").write_text(
        "SceneManager._screenWidth = 1024;\n"
    )
    assert detect_native_size(str(folder)) == NativeSize(816, 624, "MV default")


